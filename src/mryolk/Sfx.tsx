/**
 * Refuse a mix that has quietly become noise.
 *
 * Checked at module load so it fails the build rather than the render. The window is
 * generous — this only catches a section that has genuinely run away, not deliberate comic
 * clustering like the five "Gone" beats.
 */
function assertDensity(cues: Cue[]): void {
  const sorted = [...cues].sort((a, b) => a.at - b.at);
  const WINDOW = 10;
  const MAX_IN_WINDOW = 9;
  for (let i = 0; i < sorted.length; i++) {
    const n = sorted.filter((c) => c.at >= sorted[i].at && c.at < sorted[i].at + WINDOW).length;
    if (n > MAX_IN_WINDOW) {
      throw new Error(
        `${n} sound effects between ${sorted[i].at.toFixed(1)}s and ${(sorted[i].at + WINDOW).toFixed(1)}s `
        + `(ceiling is ${MAX_IN_WINDOW}). That is not punctuation any more.`,
      );
    }
  }
  for (const c of cues) {
    const g = c.gain ?? GAIN[c.sound];
    if (g > 0.32) throw new Error(`cue "${c.note}" at ${g} would compete with the narration`);
  }
}

