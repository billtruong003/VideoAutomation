type Sound =
  | 'pop' | 'tick' | 'whoosh' | 'ding' | 'cash' | 'paper' | 'stamp' | 'thud'
  | 'crack' | 'boing' | 'error' | 'vanish' | 'sparkle' | 'crash' | 'flush' | 'swell';

/**
 * Per-category ceilings.
 *
 * A category exists so that a level decision is made ONCE for a kind of sound rather than
 * re-argued at every one of the eighty-odd cue sites, where it would drift.
 */
const GAIN: Record<Sound, number> = {
  pop: 0.13,
  tick: 0.09,
  whoosh: 0.12,
  ding: 0.15,
  cash: 0.16,
  paper: 0.13,
  stamp: 0.18,
  thud: 0.18,
  crack: 0.24,
  boing: 0.20,
  error: 0.17,
  vanish: 0.14,
  sparkle: 0.12,
  crash: 0.26,
  flush: 0.30,
  swell: 0.08,
};

type Cue = { at: number; sound: Sound; gain?: number; note: string };

/** Absolute seconds of a word, for anchoring a cue. `off` nudges by seconds, not frames. */
const W = (from: number, to: number, word: string, nth = 1, off = 0): number => {
  const { start, end } = spanOf(from, to);
  let seen = 0;
  for (const w of WORDS) {
    if (w.start < start - 0.001 || w.end > end + 0.001) continue;
    // Same matcher the scenes use, so a cue and the visual it punctuates can never
    // disagree about which token counts as "the word".
    if (!wordMatches(w.text, word)) continue;
    seen += 1;
    if (seen === nth) return w.start + off;
  }
  throw new Error(`sfx anchor "${word}" #${nth} not spoken in segments ${from}..${to}`);
};

