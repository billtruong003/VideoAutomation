/**
 * Sfx.tsx — sound effects, anchored to spoken words.
 *
 * Order is not negotiable and mirrors the rest of the pipeline: the narration was processed
 * and LOCKED first, the transcript came from that locked file, and only now do effects get
 * hung off those timestamps. Nothing here can move the narration.
 *
 * ------------------------------------------------------------------------- mix policy
 *
 * NARRATION ALWAYS WINS. It renders at unity; nothing in this table exceeds 0.30, and most
 * sit near 0.14. A sound effect that makes a viewer miss a word has cost more than it gave,
 * every time, without exception. The one place levels rise is where a cue lands in a genuine
 * pause and is carrying a punchline.
 *
 * DENSITY IS A FUNCTION OF THE SECTION. This is fourteen minutes, not forty seconds. An
 * effect every second would be exhausting by minute three and would flatten the sections that
 * are meant to feel different. So:
 *
 *   explanation      almost silent; a tick when a diagram element lands, nothing else
 *   mechanism        quiet clicks and paper, marking the steps of an argument
 *   comedy           denser and louder, because the density IS the comic timing
 *   turning points   one deliberate sound, alone, in space
 *
 * `assertDensity()` enforces the ceiling at module load rather than trusting judgement — it
 * is very easy to add "just one more" thirty times across a long edit and never notice that a
 * section has become noise.
 *
 * Every sound is procedurally generated by `tools/mryolk/make-sfx.mjs`. Original work, nothing
 * to license, nothing to attribute, nothing that can trip Content ID.
 */

